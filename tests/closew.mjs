import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 800 } });
await page.goto("http://localhost:5317/?example=IDE");
const tabs = async () => (await page.locator(".carreau-pane", { has: page.locator(".carreau-tab", { hasText: /^main\.ts$/ }) }).locator(".carreau-tab").allTextContents()).join(",");
await page.locator(".carreau-tab", { hasText: /^view\.ts$/ }).click();
await page.keyboard.down("Alt"); await page.keyboard.press("KeyQ"); await page.keyboard.press("KeyW"); await page.keyboard.up("Alt");
await page.waitForTimeout(150);
console.log("held Alt+Q W:", await tabs());
await page.keyboard.down("Alt"); await page.keyboard.press("KeyQ"); await page.keyboard.press("KeyW"); await page.keyboard.up("Alt");
await page.waitForTimeout(150);
console.log("held, again W:", await tabs());
await browser.close();
